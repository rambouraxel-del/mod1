def _recolor(rows, mapping):
    """Copie d'une grille en remplacant certains caracteres (variante de couleur)."""
    return ["".join(mapping.get(ch, ch) for ch in row) for row in rows]


def _overlay(rows, marks):
    """Pose des caracteres a des positions explicites (x, y) -> caractere."""
    out = [list(r) for r in rows]
    for (x, y), ch in marks.items():
        out[y][x] = ch
    return ["".join(r) for r in out]


