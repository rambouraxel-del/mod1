def _bowl(content):
    """content: 4 lignes de 16 caracteres ou moins, posees au-dessus du bol."""
    rows = [D16] * 16
    for i, line in enumerate(content):
        rows[3 + i] = line
    for i, line in enumerate(BOWL_BASE):
        rows[7 + i] = line
    return rows


