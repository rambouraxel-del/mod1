# PARTICULES: insectes (sprites 8x8 centres dans un canevas 16x16)
# ---------------------------------------------------------------------------

def _centered8(rows8):
    """Pose une grille 8x8 au centre d'un canevas 16x16 (marge de 4 px)."""
    empty = ["."] * 16
    out = []
    for y in range(16):
        if 4 <= y < 12:
            row = "....%s....".replace("%s", rows8[y - 4])
        else:
            row = "".join(empty)
        out.append(row)
    return out


